#!/usr/bin/env node
// Assembles the living brand kit page: kit/src/shell.html + kit/src/sections/*.html -> kit/index.html
// Zero dependencies. Run: node brand/kit/build.mjs   (or `node brand/build.mjs` for tokens + kit)
//
// Section files start with one front-matter comment:
//   <!-- id: colour | title: Colour | group: Foundations -->
// Inside any HTML, <!--@include path/to/file.svg--> inlines a file (path relative to brand/),
// and <!--@icon name--> inlines a UI icon from brand/icons/ui wrapped in .d-icon.
// A section may ship its own css/sections/<name>.css and js/sections/<name>.js; they are linked automatically.

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { dirname, join, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const KIT = dirname(fileURLToPath(import.meta.url))
const BRAND = join(KIT, '..')
const read = (p) => readFileSync(p, 'utf8')

const INCLUDE = /<!--@include\s+([^\s]+)\s*-->/g
// <!--@icon name-->  is short for a decorative UI icon:  <span class="d-icon" aria-hidden="true">…icons/ui/name.svg…</span>
// <!--@icon name sm|lg|xl-->  adds the size modifier.
const ICON = /<!--@icon\s+([a-z0-9-]+)(?:\s+(sm|lg|xl))?\s*-->/g
function inline(html, from) {
  html = html.replace(ICON, (_, name, size) => {
    const p = join(BRAND, 'icons', 'ui', `${name}.svg`)
    if (!existsSync(p)) throw new Error(`${from}: icon not found: icons/ui/${name}.svg`)
    return `<span class="d-icon${size ? ` d-icon--${size}` : ''}" aria-hidden="true">${read(p).trim()}</span>`
  })
  return html.replace(INCLUDE, (_, rel) => {
    const p = join(BRAND, rel)
    if (!existsSync(p)) throw new Error(`${from}: include not found: ${rel}`)
    return read(p)
      .replace(/<\?xml[^>]*\?>\s*/g, '')
      .replace(/<!DOCTYPE[^>]*>\s*/gi, '')
      .trim()
  })
}

// brand/css/components.css: one @import per component file, so adding a component is adding a file.
const componentDir = join(BRAND, 'css', 'components')
const componentFiles = readdirSync(componentDir).filter((f) => f.endsWith('.css')).sort()
writeFileSync(
  join(BRAND, 'css', 'components.css'),
  `/* GENERATED by brand/kit/build.mjs: one import per file in css/components. Do not edit. */\n${componentFiles
    .map((f) => `@import url("components/${f}");`)
    .join('\n')}\n`,
)

// `--only <section-name>` builds kit/preview-<section-name>.html with just that section (for checking one section).
const onlyAt = process.argv.indexOf('--only')
const only = onlyAt > -1 ? process.argv[onlyAt + 1] : null

const sectionDir = join(KIT, 'src', 'sections')
const sections = readdirSync(sectionDir)
  .filter((f) => f.endsWith('.html'))
  .filter((f) => !only || basename(f, '.html') === only)
  .sort()
  .map((file) => {
    const raw = read(join(sectionDir, file))
    const fm = raw.match(/^\s*<!--\s*([^>]*?)\s*-->/)
    if (!fm) throw new Error(`${file}: missing front-matter comment`)
    const meta = Object.fromEntries(
      fm[1].split('|').map((kv) => {
        const i = kv.indexOf(':')
        return [kv.slice(0, i).trim(), kv.slice(i + 1).trim()]
      }),
    )
    if (!meta.id || !meta.title) throw new Error(`${file}: front matter needs id and title`)
    const name = basename(file, '.html')
    return { file, name, meta, html: inline(raw.slice(fm[0].length).trim(), file) }
  })

const groups = []
for (const s of sections) {
  const g = s.meta.group ?? ''
  let group = groups.find((x) => x.name === g)
  if (!group) groups.push((group = { name: g, items: [] }))
  group.items.push(s)
}

const nav = groups
  .map(
    (g) =>
      `<div class="kit-nav__group">${g.name ? `<p class="kit-nav__label">${g.name}</p>` : ''}<ul>${g.items
        .map((s) => `<li><a href="#${s.meta.id}">${s.meta.title}</a></li>`)
        .join('')}</ul></div>`,
  )
  .join('\n')

const body = sections
  .map((s) => `<section class="kit-section" id="${s.meta.id}" data-section="${s.name}" aria-labelledby="${s.meta.id}-title">\n${s.html}\n</section>`)
  .join('\n\n')

const styles = sections
  .filter((s) => existsSync(join(KIT, 'css', 'sections', `${s.name}.css`)))
  .map((s) => `<link rel="stylesheet" href="css/sections/${s.name}.css">`)
  .join('\n  ')

const scripts = sections
  .filter((s) => existsSync(join(KIT, 'js', 'sections', `${s.name}.js`)))
  .map((s) => `<script defer src="js/sections/${s.name}.js"></script>`)
  .join('\n  ')

const out = inline(read(join(KIT, 'src', 'shell.html')), 'shell.html')
  .replace('<!--NAV-->', nav)
  .replace('<!--SECTIONS-->', body)
  .replace('<!--SECTION_STYLES-->', styles)
  .replace('<!--SECTION_SCRIPTS-->', scripts)

if (only && !sections.length) throw new Error(`--only ${only}: no such section in kit/src/sections`)
const target = join(KIT, only ? `preview-${only}.html` : 'index.html')
writeFileSync(target, `<!-- GENERATED by brand/kit/build.mjs from kit/src. Edit the sources, not this file. -->\n${out}`)
console.log(`kit: ${sections.length} sections, ${componentFiles.length} components -> ${target}`)
